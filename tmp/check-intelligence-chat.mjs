import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5180/observatory-v2#/intelligence/client/canopy/current?lens=intelligence%3Achat');
await page.getByRole('heading',{name:'Talk through your intelligence.'}).waitFor();
await page.getByRole('button',{name:'Prepare a weekly update',exact:true}).click();
await page.getByRole('checkbox',{name:'Social media',exact:true}).uncheck();
await page.getByRole('combobox',{name:'Draft format'}).click();
await page.getByRole('option',{name:'Action plan',exact:true}).click();
