const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://localhost:5173/#/brand-tools');
    const search = page.getByRole('combobox', { name: 'Search brand tools' });
    await search.fill('nothing matches');
    await page.getByText('No tools found. Try “citation”.').waitFor();
    await search.fill('citation');
    await search.press('Enter');
    const imageButton = page.getByRole('button', { name: 'Export image', exact: true });
    await imageButton.waitFor();
    await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Export image')?.disabled);
    await page.getByRole('textbox', { name: 'Author', exact: true }).fill('Ada Lovelace');
    await page.reload();
    assert.equal(await page.getByRole('textbox', { name: 'Author', exact: true }).inputValue(), 'Ada Lovelace');
    await page.getByRole('tab', { name: 'Landscape' }).click();
    await page.waitForFunction(() => document.querySelector('canvas[role=img]')?.width === 1350);
    await page.waitForTimeout(800);
    const imageDownloadPromise = page.waitForEvent('download');
    await imageButton.click();
    const imageDownload = await imageDownloadPromise;
    await imageDownload.saveAs('tmp/citation-export.png');
    const png = await fs.readFile('tmp/citation-export.png');
    assert.equal(png.readUInt32BE(16), 1350);
    assert.equal(png.readUInt32BE(20), 1080);
    await page.getByRole('combobox', { name: 'Video duration', exact: true }).click();
    await page.getByRole('option', { name: '3 seconds', exact: true }).click();
    const videoDownloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export video', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Citation', exact: true }).isDisabled(), true);
    const videoDownload = await videoDownloadPromise;
    const videoPath = `tmp/${videoDownload.suggestedFilename()}`;
    await videoDownload.saveAs(videoPath);
    assert.ok((await fs.stat(videoPath)).size > 10000);
    const bytes = await fs.readFile(videoPath);
    const metadata = await page.evaluate(async ({ base64, type }) => {
      const blob = await (await fetch(`data:${type};base64,${base64}`)).blob();
      const video = document.createElement('video');
      video.src = URL.createObjectURL(blob);
      await new Promise((resolve, reject) => { video.onloadedmetadata = resolve; video.onerror = reject; });
      const result = { width: video.videoWidth, height: video.videoHeight, duration: video.duration };
      URL.revokeObjectURL(video.src);
      return result;
    }, { base64: bytes.toString('base64'), type: videoPath.endsWith('mp4') ? 'video/mp4' : 'video/webm' });
    assert.equal(metadata.width, 1350);
    assert.equal(metadata.height, 1080);
    assert.ok(metadata.duration >= 2.5);
    console.log('Video metadata', metadata);
    const quote = page.getByRole('textbox', { name: 'Citation', exact: true });
    await quote.fill('');
    assert.equal(await imageButton.isDisabled(), true);
    await quote.fill('A line\n'.repeat(65));
    await page.getByRole('alert').waitFor();
    assert.equal(await imageButton.isDisabled(), true);
    await quote.fill('The easiest way to destroy trust is to pretend certainty.');
    await page.getByRole('tab', { name: 'Portrait' }).click();
    await page.screenshot({ path: 'tmp/brand-desktop-verified.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'tmp/brand-mobile-verified.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByRole('link', { name: 'All tools' }).click();
    await page.getByRole('main', { name: 'Moonvine brand tools', exact: true }).waitFor();
    assert.equal(await page.locator('body > canvas').count(), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: search, keyboard launch, persistence, formats, PNG/video downloads, validation, mobile overflow, cleanup, browser errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
